/** Точка на сфері. Структурно сумісна з `RoutePoint` і з полями `Vessel`. */
export interface GeoPoint {
  readonly lat: number;
  readonly lon: number;
}

// Імена з оригіналу (`dms.js:330`): азимут приводиться пилкоподібною функцією з
// амплітудою `a` і періодом `p`. Числа лишаються тут, а не стають одним 360,
// саме щоб порт читався поряд із джерелом.
const AMPLITUDE = 180;
const PERIOD = 360;

function toRadians(degrees: number): number {
  return (degrees * Math.PI) / 180;
}

function toDegrees(radians: number): number {
  return (radians * 180) / Math.PI;
}

/**
 * Приведення до домену [0, 360).
 *
 * Існує тому, що `%` у JavaScript — ОСТАЧА, а не модуль: `-170 % 360` дає
 * `-170`, тобто значення поза доменом, який ТЗ оголошує для `courseDeg`.
 * Вираз `((x % n) + n) % n` — саме модуль.
 *
 * Ранній вихід для вже коректного значення — з оригіналу: він береже від
 * похибки, яку внесла б зайва арифметика над числом, що й так на місці.
 *
 * Вираз тіла — теж дослівно з оригіналу, і спрощувати його до
 * `((x % 360) + 360) % 360` не можна, хоч алгебраїчно це те саме. ВИМІРЯНО на
 * домені, який єдиний і здатен видати `atan2`, — (−180, 0), 2 000 000
 * рівномірних точок: 96 244 значення розходяться між двома формами, максимум
 * 5.68e-14°. (Кількість залежить від вибірки, максимум — ні.) Для показу
 * різниця невидима, її з'їдає округлення в картці; але порт, що розходиться з
 * джерелом на власному домені, перестає бути портом — і наступний, хто звірить
 * його з `dms.js`, не матиме як зрозуміти, навмисно це чи ні.
 *
 * ЦЕ НЕ ТЕ САМЕ, ЩО `normalizeCourseDeg` у `vessel-format.ts`, і злити їх не
 * можна: та працює на шарі показу, з уже коректним `courseDeg`, і ОКРУГЛЮЄ;
 * ця працює до того, як число стане `courseDeg`, і нічого не округлює.
 * Прибрати цю — означає віддати в структуру `courseDeg: -133.7`, після чого
 * `Math.round(-133.7) % 360` надрукує "-134°", а значок поверне не в той бік.
 * Ні `tsc`, ні лінтер цього не побачать: `-134` — валідне `number`.
 */
function wrap360(degrees: number): number {
  if (degrees >= 0 && degrees < PERIOD) {
    return degrees;
  }

  return ((((2 * AMPLITUDE * degrees) / PERIOD) % PERIOD) + PERIOD) % PERIOD;
}

/**
 * Початковий азимут від `from` до `to`, у градусах від півночі, у [0, 360).
 *
 * САМЕ ПОЧАТКОВИЙ. На великому колі початковий і кінцевий азимути різні
 * (для опорної пари geodesy — 156.2° проти 157.9°), а ТЗ називає початковий.
 *
 * Для збіжних точок повертає `null` — і це свідоме розходження з оригіналом,
 * який повертає `NaN`. Контракт ТЗ — `number | null`: `null` рендериться як
 * нейтральний значок і "Немає даних", а `NaN` не рендериться ніяк.
 */
export function initialBearingDeg(from: GeoPoint, to: GeoPoint): number | null {
  if (from.lat === to.lat && from.lon === to.lon) {
    return null;
  }

  // tanθ = sinΔλ⋅cosφ2 / cosφ1⋅sinφ2 − sinφ1⋅cosφ2⋅cosΔλ
  // (коментар і порядок дій — з оригіналу; виведення формули див. там)
  const lat1 = toRadians(from.lat);
  const lat2 = toRadians(to.lat);
  const deltaLon = toRadians(to.lon - from.lon);

  const x = Math.cos(lat1) * Math.sin(lat2) - Math.sin(lat1) * Math.cos(lat2) * Math.cos(deltaLon);
  const y = Math.sin(deltaLon) * Math.cos(lat2);

  return wrap360(toDegrees(Math.atan2(y, x)));
}
