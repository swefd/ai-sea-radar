// район входить.

/** Точка маршруту. Структурно збігається з `GeoPoint` у `lib/geo.ts`. */
export interface RoutePoint {
  readonly lat: number;
  readonly lon: number;
}

export interface DemoRoute {
  readonly id: string;
  readonly name: string;
  /** Вузли. Літерал, а не похідна від геометрії — див. §10 проєктного рішення. */
  readonly speedKnots: number;
  /** 8-12 точок усередині району; жодні дві сусідні не збігаються. */
  readonly points: readonly RoutePoint[];
}

