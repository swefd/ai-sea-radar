#!/bin/sh
# Резолвер інтерпретатора для хуків Claude Code.
#
# Хук не успадковує середовище інтерактивної оболонки: ні nvm, ні його PATH.
# Голий `npx tsc` усередині хука повідомив би UNRUNNABLE із неправильної причини —
# а це найгірший різновид брехні, бо виглядає як висновок про код.
#
# САМІ ЛИШЕ ВБУДОВАНІ КОМАНДИ — без dirname, sed, ls, cat: ворожий або порожній
# PATH не має ламати саме визначення шляхів.
#
# stdin НЕ ЧИТАЄТЬСЯ: на ньому лежить JSON події, і він мусить дійти до .mjs незайманим.
# Єдиний `read` нижче має явний редирект із .nvmrc.
set -u

# --- голосна відмова -------------------------------------------------------
# Ніколи тихий ненульовий вихід: fail open, але видимо (та сама логіка, що §6.3 п.4).
# Другий аргумент — подробиця ЛИШЕ для stderr. У JSON вона не потрапляє свідомо:
# туди йдуть тільки рядки, написані тут, бо шлях чи вміст файлу можуть містити
# лапку або зворотний слеш і зробити stdout нерозбірним саме тоді, коли його
# читають, щоб дізнатися про поломку.
fail_loud() {
  printf '{"systemMessage":"ХУК НЕ ЗАПУСТИВСЯ: %s. Перевірка НЕ виконувалась — не вважай її зеленою."}\n' "$1"
  printf 'node.sh: %s%s\n' "$1" "${2:-}" >&2
  exit 0
}

[ "$#" -gt 0 ] || fail_loud "викликано без аргументів"

# --- каталоги, без dirname -------------------------------------------------
# Кожен зріз перевіряється окремо: `${var%/*}` лишає рядок БЕЗ ЗМІН, коли '/' у
# ньому вже немає. Без цих перевірок виклик `.claude/hooks/node.sh` (без './')
# зупиняв би зріз на `.claude` — і `.nvmrc` шукався б за `.claude/.nvmrc`, а в
# PATH лягав би неіснуючий `.claude/node_modules/.bin`. Виміряно: така форма
# мовчки бігла іншою версією, ніж дві інші (R-149).
hook_dir=${0%/*}
[ "$hook_dir" = "$0" ] && hook_dir=.
claude_dir=${hook_dir%/*}
[ "$claude_dir" = "$hook_dir" ] && claude_dir=.
project_dir=${claude_dir%/*}
[ "$project_dir" = "$claude_dir" ] && project_dir=.

# --- бажаний мажор: .nvmrc — ЄДИНЕ місце, де версія зафіксована (CLAUDE.md) --
# Запасного числа немає свідомо: захардкоджений мажор мовчки підміняв би єдине
# джерело істини, а файл читався б для вигляду (R-152). Тому нечитабельний,
# порожній або незрозумілий .nvmrc — голосна відмова, а не припущення. `lts/*` —
# легальний синтаксис nvm, якого цей резолвер не вміє: сказати «не вмію» чесніше,
# ніж побігти «чимось».
#
# Читається .nvmrc того дерева, де лежить САМ скрипт, а не того, що перевіряється:
# дерево для перевірки хуки беруть із поля `cwd` події (R-20), і в worktree це
# різні дерева. Розкол свідомий; тут потрібна версія, якою запускати сам хук.
[ -r "$project_dir/.nvmrc" ] || fail_loud "не прочитано .nvmrc поряд зі скриптом" " (шукав у $project_dir)"
nvmrc=''
# `read` повертає ненуль на файлі БЕЗ кінцевого переводу рядка, але змінну при
# цьому вже заповнив — тож невдача ігнорується, а порожнечу ловить розбір нижче.
IFS= read -r nvmrc < "$project_dir/.nvmrc" || :
want=${nvmrc#v}
want=${want%%.*}
case $want in
  '' | *[!0-9]*)
    fail_loud "мажор у .nvmrc не розібрано — підтримується 24 або v24.21.0, не lts/*"
    ;;
esac

major_of() {
  mv_out=$("$1" -v 2>/dev/null) || return 1
  mv_out=${mv_out#v}
  mv_out=${mv_out%%.*}
  [ -n "$mv_out" ] || return 1
  printf '%s' "$mv_out"
}

# --- пошук інтерпретатора: абсолютні шляхи спершу, PATH — останнім ----------
# PATH у хука — це дефолт машини, а не пін із .nvmrc, і єдине джерело тут, якого
# ми не контролюємо: щоб узнати мажор кандидата з PATH, його доводиться ЗАПУСТИТИ.
# Тому PATH — запасний варіант для машини без nvm, а не перше джерело істини.
node_bin=''

# установка nvm: перелік версій вбудованим globbing, не через зовнішні утиліти.
# Якщо мінорних під потрібним мажором кілька, береться перша, яку дає глоб —
# порядок лексикографічний, не «найновіша»: .nvmrc фіксує мажор і нічого не каже
# про мінор, тож будь-яка з них задовольняє пін.
# ${HOME:-…} обов'язкове: під `set -u` неоголошений HOME обвалив би скрипт,
# а хук запускається з середовищем, якого ми не контролюємо.
for cand in "${NVM_DIR:-${HOME:-/nonexistent}/.nvm}"/versions/node/v"$want".*/bin/node; do
  [ -x "$cand" ] || continue
  # Назві теки НЕ вірять, як і двом сусіднім гілкам: у підробленому чи
  # пошкодженому дереві `v24.9.0/bin/node` може звітувати чужий мажор, а
  # виконуваний не-бінарник узагалі вийшов би 127 — тобто тихим ненульовим
  # виходом, якого за контрактом не існує (R-151). Ціна — один spawn на кандидата.
  [ "$(major_of "$cand")" = "$want" ] || continue
  node_bin=$cand
  break
done

# типові системні розташування — теж абсолютні, тож ворожий PATH на них не впливає
if [ -z "$node_bin" ]; then
  for cand in /opt/homebrew/bin/node /usr/local/bin/node /usr/bin/node; do
    [ -x "$cand" ] || continue
    [ "$(major_of "$cand")" = "$want" ] || continue
    node_bin=$cand
    break
  done
fi

# останнє джерело — те, що в PATH
if [ -z "$node_bin" ]; then
  if cand=$(command -v node 2>/dev/null) && [ -x "$cand" ]; then
    [ "$(major_of "$cand")" = "$want" ] && node_bin=$cand
  fi
fi

# Свідомо НЕ запускаємось на чужому мажорі. Вердикт, отриманий не тим Node, —
# це твердження про код, якого ніхто не перевіряв тим інтерпретатором, що заявлений.
[ -n "$node_bin" ] || fail_loud "не знайдено Node major ${want} (.nvmrc)"

node_dir=${node_bin%/*}
orig_path=${PATH:-}
# Каталог знайденого node — першим, щоб `node` усередині .mjs означав саме його.
# Далі $PWD і лише потім каталог скрипта: у worktree node_modules активного дерева
# лежить під $PWD, і він має вигравати в того, що поруч зі скриптом.
# Кожна складова — із запасним значенням: під `set -u` порожній PATH або незаданий
# PWD обвалили б скрипт саме там, де він мусить відмовляти голосно.
PATH=$node_dir:${PWD:-.}/node_modules/.bin
# Каталог скрипта додається, лише коли він НЕ збігається з cwd: за виклику без
# './' project_dir дорівнює '.', і запис був би дублем того, що вже стоїть вище,
# до того ж ВІДНОСНИМ — його значення мінялося б разом із cwd процесу, який ним
# скористається.
[ "$project_dir" = "." ] || PATH=$PATH:$project_dir/node_modules/.bin
# Успадкований PATH дописується в кінець, а не затирається. Порожній не дописується
# зовсім: кінцева двокрапка означає порожній запис, тобто поточну теку в PATH.
[ -z "$orig_path" ] || PATH=$PATH:$orig_path
export PATH

exec "$node_bin" "$@"
