// Спільна варта вхідної точки для всього шару: `run.mjs`, `hash.mjs` і обидві
// перевірки під `checks/`. До цього модуля копій було чотири — дві правильні й дві
// наївні, — і мовчали саме наївні.
//
// Правило трьох спрацювало буквально: коли копій було дві, `no-secrets.mjs` записав,
// що винесення відкладено до третього випадку. Третім і четвертим виявилися не нові
// перевірки, а `run.mjs` і `hash.mjs`, у яких ту саму діру виміряли окремо.
import { realpathSync } from 'node:fs';

/**
 * Чи запущено ЦЕЙ модуль як програму, а не імпортовано?
 *
 * Ім'я файлу приходить параметром, бо `import.meta` доступний лише в самому модулі:
 * викликач передає власне `import.meta.filename`. Інакше функція відповідала б про
 * себе, а питання ставлять про викликача.
 *
 * Обидва боки — крізь `realpathSync`, і це не обережність про запас. Node резолвить
 * URL модуля крізь симлінк, а `process.argv[1]` лишає як дали, тож пряме порівняння
 * під симлінком не кликало `main()` ВЗАГАЛІ: нуль байтів виводу й EXIT=0, а `run.mjs`
 * робить із нуля PASSED. Виміряно на справжніх файлах цього дерева, не виведено з
 * документації: під симлінком `run.mjs` і `hash.mjs` давали нуль байтів і EXIT=0 там,
 * де реальний шлях давав ненульовий вивід і EXIT=1. Числа байтів сюди не виписані
 * навмисно — вони містять абсолютний шлях у стеку, тобто залежать від теки запуску;
 * несуче тут «нуль проти ненуля», і воно від теки не залежить.
 *
 * Порівнюються саме ШЛЯХИ, а не URL: конкатенація `file://…` ламається на пробілах і
 * не-ASCII у шляху, а тека worktree — це шлях, який обирали не ми.
 *
 * @param {string} moduleFilename — `import.meta.filename` викликача.
 * @returns {boolean}
 */
export function isEntryPoint(moduleFilename) {
  const invoked = process.argv[1];
  // Не задано — значить, файл не запускали: `node --eval`, REPL, імпорт із тесту.
  if (invoked === undefined) return false;
  try {
    return realpathSync(invoked) === realpathSync(moduleFilename);
  } catch {
    // Шляху не існує (видалили між стартом і цим рядком) — це не запуск нас.
    return false;
  }
}
