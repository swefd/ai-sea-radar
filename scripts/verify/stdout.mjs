// Повний синхронний запис у сирий дескриптор.
//
// Виміряно на цьому дереві: `process.stdout.write(текст)` із негайним
// `process.exit(0)` доставляє в трубу рівно 65536 байтів із будь-якого більшого
// обсягу — решту Node тримає в асинхронному буфері, і `exit` його відкидає.
// Для хука це найгірша з можливих форм втрати: читач отримує текст, що
// обривається посеред слова, і НЕ БАЧИТЬ, що його обірвано, — тобто повний
// вигляд неповного знання. Той самий клас, що й мовчазне зелене.
//
// Модуль спільний, а не копія всередині хука, і це рішення, а не звичка:
// Stop-гейт друкує свій вивід так само, а копія, яка розійдеться з оригіналом,
// розійдеться МОВЧКИ — рівно як розійшлися чотири копії варти вхідної точки до
// того, як їх звели в `isEntryPoint`. Ціна помилки тут не «трохи не так
// відформатовано», а «частини виводу немає».
import { writeSync } from 'node:fs';

// Синхронний сон без залежностей: `writeSync` не повертає керування в event
// loop, тож `setTimeout` тут ніколи б не спрацював — до черги таймерів справа
// не дійшла б. `Atomics.wait` на головному потоці Node дозволений (на відміну
// від браузера) і чекає рівно задану кількість мілісекунд.
const IDLE_SLOT = new Int32Array(new SharedArrayBuffer(4));
const EAGAIN_PAUSE_MS = 1;

/**
 * Записати ВЕСЬ текст у дескриптор `fd` або чесно сказати, скільки дійшло.
 *
 * `writeSync` має право записати менше, ніж просили (часткова доставка в
 * трубу), тож єдиний виклик без циклу — це мовчазна втрата хвоста.
 *
 * @param {number} fd — дескриптор (1 — stdout).
 * @param {string} text — текст; у байти переводиться тут, бо межа обрізання
 *   в трубі байтова, а довжина рядка в UTF-16 до неї стосунку не має.
 * @param {(fd: number, buffer: Buffer, offset: number, length: number) => number} write
 *   — шов для тестів. Часткового запису й EAGAIN не викликати ззовні: без шва
 *   цикл і обидві гілки лишалися б твердженням, якого ніхто не перевіряв, —
 *   а сáме вони тут і несуть.
 * @returns {number} скільки БАЙТІВ дійшло; менше за довжину — лише коли
 *   читача не стало.
 */
export function writeAllSync(fd, text, write = writeSync) {
  const buffer = Buffer.from(text, 'utf8');
  let written = 0;
  while (written < buffer.length) {
    try {
      written += write(fd, buffer, written, buffer.length - written);
    } catch (error) {
      if (error.code === 'EAGAIN') {
        // Труба повна, а дескриптор неблокувальний. Це не помилка, а «спробуй
        // пізніше»: вийти тут означало б утратити хвіст саме тоді, коли його
        // найбільше — на довгому виводі.
        Atomics.wait(IDLE_SLOT, 0, 0, EAGAIN_PAUSE_MS);
        continue;
      }
      // Читача не стало (сесію вбито, труба закрита з того боку). Це єдиний
      // випадок, коли неповний запис не брехня: адресата вже немає.
      if (error.code === 'EPIPE') return written;
      throw error;
    }
  }
  return written;
}
