// Стереже правило з CLAUDE.md і reference/CLAUDE.md: «Never `import` from
// `../reference/...`, in app code or tests, at runtime or at type level».
// Записане тричі, не стережене нічим — саме той «documented-but-unenforced»
// інваріант, заради якого спека §4 завела три власні рядки.
import { readFileSync, realpathSync } from 'node:fs';
import path from 'node:path';

import { isSourcePath, listRepoFiles } from '../hash.mjs';

/**
 * Периметр сканування — це периметр свіжості з `hash.mjs`, звужений за розширенням.
 * Власного списку тек тут немає навмисно. Доки списки були два, вони збігалися лише
 * домовленістю, і три кореневі конфіги — `next.config.ts`, `playwright.config.ts`,
 * `eslint.config.mjs` — у периметр хеша входили, а в периметр сканування ні:
 * імпорт із reference/ у `next.config.ts` давав «порушень немає» й EXIT=0
 * (виміряно). Тепер це один і той самий `isSourcePath`, тож розійтися вони більше
 * не можуть, а звуження лишається одне, назване й записане нижче — розширення файлу.
 */
const SCAN_EXTENSIONS = [
  '.ts', '.tsx', '.mts', '.cts', '.js', '.jsx', '.mjs', '.cjs',
  // @import у CSS так само вміє вказати за межі проєкту.
  '.css',
];

/** Літеральний специфікатор у лапках будь-якого з трьох видів. */
const SPECIFIER = String.raw`(['"\`])([^'"\`\n]*)\1`;

/**
 * Статичні форми — і єдине джерело правди про те, що саме перевірка впізнає:
 * `proves` рядка реєстру тепер посилається сюди, а не називає число. Число в
 * прозі не пінило нічого й старіло тричі поспіль; масив збрехати про власну
 * довжину не вміє.
 *
 * Обчислений шлях сюди не потрапляє за визначенням — це записано в blindSpot
 * рядка реєстру й не лікується тут.
 *
 * `import … from` і `export … from` розділені на два імені навмисно, а не злиті
 * в одне `(?:import|export)`. Ім'я форми потрапляє у вивід перевірки, і рядок
 * `bad.ts:2: import-from →` на реекспорті називав би не ту конструкцію. Ціна
 * злиття видно й у тесті: шість різних синтаксичних форм давали б лише п'ять
 * різних імен, тож твердження «кожна форма спіймана СВОЇМ матчером» стало б
 * недоказовним.
 */
const FORMS = [
  // `[^;]*?`, а не `[^;\n]*?`: крапка з комою лишається бар'єром, а перенос рядка
  // перестає ним бути. Інакше інструкція з `import {` на одному рядку і `} from '…'`
  // на іншому не збігається з жодною формою — а це панівне форматування тут.
  { name: 'import-from', re: new RegExp(String.raw`\bimport\b[^;]*?\bfrom\s*` + SPECIFIER, 'g') },
  { name: 'export-from', re: new RegExp(String.raw`\bexport\b[^;]*?\bfrom\s*` + SPECIFIER, 'g') },
  { name: 'import-bare', re: new RegExp(String.raw`\bimport\s+` + SPECIFIER, 'g') },
  { name: 'import-dynamic', re: new RegExp(String.raw`\bimport\s*\(\s*` + SPECIFIER, 'g') },
  // `(?:\.resolve)?` — бо `require.resolve('…')` теж дає шлях до файлу під
  // `reference/`, а `proves` називало `require` без застережень (виміряно: без
  // цих семи символів `require.resolve` мовчить).
  { name: 'require', re: new RegExp(String.raw`\brequire(?:\.resolve)?\s*\(\s*` + SPECIFIER, 'g') },
  { name: 'triple-slash', re: new RegExp(String.raw`///\s*<reference\s+[^>\n]*?path\s*=\s*` + SPECIFIER, 'g') },
  // `\s*`, а не `\s+`: `@import"…";` — валідний CSS, пробіл між директивою й
  // лапкою не обов'язковий. Правка в бік перебору, як і решта тут.
  { name: 'css-import', re: new RegExp(String.raw`@import\s*(?:url\(\s*)?` + SPECIFIER, 'g') },
];

/**
 * Прив'язка до СЕГМЕНТА шляху, не до підрядка. Інакше перевірка спрацювала б на
 * `.claude/skills/feature-sliced-design/references/…` — тека `references`, у множині,
 * і жодного стосунку до study material не має.
 */
function pointsAtReference(specifier) {
  return specifier.replace(/\\/g, '/').split('/').includes('reference');
}

/**
 * Забілює тіла коментарів, ЗБЕРІГАЮЧИ довжину тексту й усі переноси рядків.
 * Рядковий коментар — від `//` до кінця рядка (сам перенос не чіпається),
 * блоковий — від відкривального маркера до ЗАКРИВАЛЬНОГО включно; кожен
 * не-перенос стає пробілом.
 *
 * Інваріант, який ця функція тримає: забілюється ТІЛЬКИ те, що є коментарем.
 * Тому маркер, що стоїть усередині рядкового літерала чи шаблона, коментаря не
 * відкриває — регіони в лапках `'`, `"` і `` ` `` пропускаються ЦІЛКОМ, і в них
 * не забілюється нічого. Виміряно, чому це не косметика: вставка справжнього
 * порушення в кожну 5-ту позицію периметра (на базі `cf3c0c7` — 672 позиції,
 * 29 файлів) до цієї правки не знаходилася в 61 позиції з 10 файлів, а після
 * неї не знаходиться в жодній позиції живого коду — відкривальний маркер
 * усередині глоба в літералі (домашній стиль цього репозиторію) спарювався з
 * першим справжнім закривачем НИЖЧЕ й забілював усе між ними, вимикаючи
 * прохід 2 на цілому проміжку.
 *
 * Це НЕ токенізатор і повним бути не мусить. Важливий не обсяг розбору, а
 * НАПРЯМОК помилки:
 *
 * - помилитися й пропустити як літерал те, що насправді код (непарна лапка в
 *   регулярному виразі) → забілено МЕНШЕ → прохід 2 локально втрачає користь,
 *   але прохід 1 іде по сирому тексту й лишається підлогою. Втрата обмежена й
 *   хибного `PASSED` не робить;
 * - помилитися й забілити те, що не коментар → сховати справжній імпорт від
 *   проходу 2. Це напрямок, який робить хибний `PASSED`.
 *
 * Тому кожен сумнівний випадок вирішується на користь НЕ забілювати.
 *
 * Зворотного ризику — нових хибних спрацювань із самої прози — тут немає за
 * побудовою: забілюється ВСЕ тіло коментаря разом із лапками, тож у проході 2
 * коментар не здатен дати збіг. Прохід 2 знімає лише бар'єр, який коментар
 * ставив між кодом і кодом.
 *
 * Довжина — навантажений інваріант, а не охайність: номер рядка рахується як
 * `text.slice(0, match.index)`, тож з'їдений перенос зсунув би всі номери нижче.
 */
export function blankComments(text) {
  const out = text.split('');
  let i = 0;

  while (i < text.length) {
    const char = text[i];

    // Літерал пропускається ЦІЛКОМ і не забілюється: коментаря в ньому немає.
    if (char === "'" || char === '"' || char === '`') {
      i += 1;
      while (i < text.length) {
        if (text[i] === '\\') {
          i += 2;
          continue;
        }
        if (text[i] === char) {
          i += 1;
          break;
        }
        // `'` і `"` переносу рядка не переживають: непарна лапка (апостроф у
        // прозі, регулярний вираз) з'їдає щонайбільше свій рядок, а не файл.
        if (char !== '`' && text[i] === '\n') break;
        i += 1;
      }
      continue;
    }

    if (char === '/' && text[i + 1] === '/') {
      while (i < text.length && text[i] !== '\n') {
        out[i] = ' ';
        i += 1;
      }
    } else if (char === '/' && text[i + 1] === '*') {
      const end = text.indexOf('*/', i + 2);
      // Незакритий `/*` коментарем НЕ вважається — проходимо повз нього як повз
      // звичайний символ. Посилання про `tsc` і `eslint` тут не годиться:
      // `SCAN_EXTENSIONS` містить `.css`, а `.css` у цьому проєкті не парсить
      // ані те, ані те. Годиться напрямок помилки, істинний для всіх розширень:
      // пропустити незакритий `/*` означає забілити МЕНШЕ, тож прохід 2 читає
      // БІЛЬШЕ тексту й здатен лише перебрати — а перебір уже задекларований у
      // `blindSpot` рядка реєстру. Хибний `PASSED` цим шляхом недосяжний.
      // Протилежне рішення недосяжним його не лишає: читати такий `/*` як
      // коментар означало б забілити ВСЕ до кінця файлу, тобто мовчки вимкнути
      // прохід 2 на решті файлу — і ніщо про це не звітує (виміряно на базі
      // `28f4faf`: 6501 з'їдений символ, увесь рядок `no-ref-imports` і все
      // після нього).
      if (end === -1) {
        i += 1;
        continue;
      }
      const stop = end + 2;
      while (i < stop) {
        if (text[i] !== '\n') out[i] = ' ';
        i += 1;
      }
    } else {
      i += 1;
    }
  }

  return out.join('');
}

/**
 * Один прохід по тексту всіма формами. Дописує знайдене у `violations`, а `seen`
 * несе дедуплікацію МІЖ проходами, а не лише всередині одного.
 *
 * Зіставлення йде по ЦІЛОМУ тексту файлу, а не порядково. Порядкове зіставлення
 * пропускало панівне тут форматування — ключове слово й `from` на різних рядках, —
 * тобто віддавало «порушень немає» й EXIT=0 на справжньому порушенні, а `run.mjs`
 * робив із цього PASSED (виміряно на справжньому дереві).
 */
function collectForms(violations, seen, relPath, text) {
  for (const form of FORMS) {
    // Виміряно, а не припущено: жоден тест цього рядка не спростовує (R-50).
    // Регулярки з /g живуть на рівні модуля, тобто переживають і файли, і
    // виклики, — але внутрішній цикл завжди вичерпує текст до `null`, а `exec`
    // на `null` сам обнуляє `lastIndex`. Рядок лишається як страховка рівно від
    // одного майбутнього ходу: `break` усередині циклу (скажімо, «досить
    // першого порушення на файл») зробив би стан протічним, і тоді сканер
    // мовчки пропускав би порушення в наступному файлі.
    form.re.lastIndex = 0;
    let match = form.re.exec(text);
    while (match !== null) {
      const specifier = match[2];
      if (pointsAtReference(specifier)) {
        // Рядок КЛЮЧОВОГО СЛОВА, а не рядок специфікатора: у багаторядковій формі
        // людині треба початок інструкції, і для однорядкових це те саме число.
        const line = text.slice(0, match.index).split('\n').length;
        // Роздільник — пробіл, і цього досить: `line` завжди цифри, тож перший
        // пробіл у ключі завжди той самий, скільки б їх не було в специфікаторі.
        const key = `${line} ${specifier}`;
        if (!seen.has(key)) {
          seen.add(key);
          violations.push({ file: relPath, line, form: form.name, specifier });
        }
      }
      match = form.re.exec(text);
    }
  }
}

/**
 * ДВА проходи: сирий текст, потім текст із забіленими коментарями.
 *
 * Прохід 1 сам по собі сліпнув на тому, що CLAUDE.md прямо ВИМАГАЄ, — коментарі
 * з назвою походження поруч із портованим кодом. `[^;]*?` зроблено бар'єром
 * навмисно, але крапка з комою ВСЕРЕДИНІ коментаря інструкції не завершує, а
 * регулярка думає, що завершує. Виміряно: багаторядковий імпорт із `reference/`,
 * над яким стоїть коментар із крапкою з комою, давав `[]` — справжнє порушення
 * зникало. Заміни ту крапку з комою на кому — і те саме порушення видно.
 *
 * Прохід 2 знімає рівно цей бар'єр. Порядок проходів навантажений:
 * прохід 1 лишається ПІДЛОГОЮ (він один ловить закоментовані імпорти й
 * `/// <reference>`, який сам є коментарем), а прохід 2 тільки ДОДАЄ. Тому
 * наївність забілення нічого не коштує, а ім'я форми при збігу в обох проходах
 * лишає прохід 1 — його опис конструкції точніший.
 */
export function scanText(relPath, text) {
  const violations = [];
  // Одне порушення вміє збігтися з кількома формами й у кількох проходах. Ключ —
  // трійка file+line+specifier (файл тут один), а порядок циклів лишає ПЕРШЕ
  // ім'я в порядку FORMS: воно найточніше описує конструкцію.
  //
  // Схлопується РІВНО той випадок, де обидва збіги лягли на один рядок: голий
  // `@import '…'` у .css ловиться і як import-bare, і як css-import.
  //
  // Не схлопується — і це навмисно — випадок, де форма дотягнулася до `from`
  // НИЖЧОГО рядка: `export const a = 1` без крапки з комою над справжнім імпортом
  // дає два рядки звіту, `export-from@1` і `import-from@2`, на одне порушення
  // (виміряно). Ключ містить `line`, а рядки різні. Зробити ключ безрядковим
  // означало б зливати й ті збіги, що описують РІЗНІ порушення з тим самим
  // специфікатором на різних рядках, — тобто недобір. Тут діє те саме правило,
  // що й в іншому місці: перебір безпечний, недобір — ні. Зайвий рядок звіту
  // бачить людина; зниклий не бачить ніхто.
  const seen = new Set();

  collectForms(violations, seen, relPath, text);
  collectForms(violations, seen, relPath, blankComments(text));

  // Цикли йдуть по формах і проходах, тож без сортування вивід ішов би групами,
  // а не згори вниз по файлу. Сортування стабільне — усередині рядка лишається
  // порядок FORMS і порядок проходів, тобто те саме перше ім'я, що вибрала
  // дедуплікація.
  return violations.sort((a, b) => a.line - b.line);
}

/**
 * Чиста функція за R-12: бере корінь, повертає перевірені файли й порушення.
 * Нічого не друкує й нічим не виходить. Тести імпортують саме її й запускають на
 * фікстурі в `os.tmpdir()` — не через підпроцес: фікстура-літерал у відстеженому
 * `.spec.ts` зробила б цю ж перевірку червоною на власному тесті.
 */
export function scanForRefImports(root) {
  const files = listRepoFiles(root).filter(
    (relPath) => isSourcePath(relPath) && SCAN_EXTENSIONS.includes(path.extname(relPath)),
  );

  const violations = [];
  for (const relPath of files) {
    violations.push(...scanText(relPath, readFileSync(path.join(root, relPath), 'utf8')));
  }

  return { files, violations };
}

function main() {
  const root = process.argv.slice(2).find((arg) => !arg.startsWith('-')) ?? process.cwd();
  const { files, violations } = scanForRefImports(root);

  for (const item of violations) {
    process.stdout.write(`${item.file}:${item.line}: ${item.form} → ${item.specifier}\n`);
  }

  if (violations.length === 0) {
    process.stdout.write(`no-ref-imports: перевірено файлів — ${files.length}, порушень немає.\n`);
    process.exit(0);
  }

  const affected = new Set(violations.map((item) => item.file)).size;
  process.stdout.write(
    `no-ref-imports: порушень — ${violations.length}, файлів із порушеннями — ${affected}.\n`,
  );
  process.exit(1);
}

// Коментарі й рядки не вирізаються навмисно: перебір безпечний, недобір — ні.
// Закоментований import із reference/ усе одно вартий того, щоб його побачили.
//
// Вхідна варта (R-22) тут обов'язкова, а не косметична: за R-12 тести імпортують
// `scanForRefImports` із цього ж файлу, і без варти імпорт запускав би `main()`
// із `process.exit()` посеред тестового процесу.
//
// Обидва боки — крізь realpathSync. URL модуля Node резолвить крізь симлінк,
// `process.argv[1]` — ні, тож пряме порівняння під симлінком не кликало `main()`
// взагалі: нуль байтів виводу, EXIT=0, і `run.mjs` робив із цього PASSED
// (виміряно). Рядок реєстру має `needs: []`, тобто за R-72 біжить неохороненим,
// і `emptyProbe` в нього немає — мовчазне зелене нікому було б спіймати.
function isEntryPoint() {
  const invoked = process.argv[1];
  // Не задано — значить, файл не запускали: `node --eval`, REPL, імпорт із тесту.
  if (invoked === undefined) return false;
  try {
    return realpathSync(invoked) === realpathSync(import.meta.filename);
  } catch {
    // Шляху не існує (видалили між стартом і цим рядком) — це не запуск нас.
    return false;
  }
}

if (isEntryPoint()) {
  try {
    main();
  } catch (error) {
    process.stderr.write(`no-ref-imports: перевірка не змогла запуститися: ${error.message}\n`);
    process.exit(2);
  }
}
