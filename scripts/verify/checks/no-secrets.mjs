// CLAUDE.md, розділ Secrets: «The AISStream key must not reach source, delivered files,
// or the screen — the client checks the handed-over files for it during acceptance».
//
// Периметр — ПЕРЕДАЧА РЕПОЗИТОРІЮ (`git ls-files -c -o --exclude-standard`), не бандл
// браузера: клієнт тут — навчальний центр, і він читає docs/, .claude/, scripts/.
// Невідстежені файли теж скануються: секрет треба спинити ДО коміту, бо після
// потрапляння в історію git його вже не «розпередати» видаленням файлу.
//
// І головне: ця перевірка НІЧОГО зі знайденого не друкує. Звіт — file:line, назва
// шаблону, довжина збігу. Інакше вона порушувала б рівно те правило, яке охороняє.
import { readFileSync } from 'node:fs';
import path from 'node:path';

import { isEntryPoint } from '../entry-point.mjs';
import { listRepoFiles } from '../hash.mjs';

/**
 * ЄДИНЕ виключення периметра (R-14): файли, чиє призначення — містити текст самих
 * шаблонів. Вони дали б самоукус — перевірка знайшла б власні регулярні вирази.
 * Виняток поіменний, перелічений, порахований у підсумку КОЖНОГО прогону (включно
 * з зеленим) і продубльований у blindSpot рядка реєстру: діра, яку видно, — не те
 * саме, що діра, якої немає.
 *
 * ПРАВИЛО: виключення обґрунтовує ВИМІРЯНА ненульова користь, ніколи передбачення,
 * що перевірка почервоніє. Кортить щось виключити — спершу виміряй, що воно ховає,
 * і постав число сюди.
 *
 * Правило написане не з принципу. Перша редакція виключала ще `package-lock.json`,
 * `skills-lock.json`, `.claude/skills/**` і `.agents/skills/**` — за передбаченням
 * «інакше червоно в перший же день». Прогін ЦИХ шаблонів по всьому, що ті
 * виключення ховали:
 *
 *   .claude/skills/     25 файлів (2 бінарні), 6302 рядки  → 0 знахідок
 *   .agents/skills/     25 файлів (2 бінарні), 6302 рядки  → 0 знахідок
 *   package-lock.json    1 файл,               6309 рядків → 0 знахідок
 *   skills-lock.json     1 файл,                 18 рядків → 0 знахідок
 *   SELF_DESCRIBING      2 файли,                702 рядки → 0 знахідок
 *                        (станом на c8d7cc5)
 *
 * КОНВЕНЦІЯ ТАБЛИЦІ: рядки пораховано так само, як їх рахує сам сканер нижче —
 * `split('\n').length`, — тож кожне число на одиницю більше за `wc -l` НА КОЖЕН
 * файл (6279 + 23 файли = 6302). Назване це навмисно: без конвенції наступний
 * вимір розійдеться з таблицею рівно на кількість файлів і читатиметься як
 * помилка запису. Саме так і сталося з рядком нижче.
 *
 * Перші чотири рядки відтворюються на будь-якому коміті; останній — ні, і це не
 * помилка запису, а властивість. Він єдиний міряє ВЛАСНІ файли перевірки, тож
 * дрейфує за побудовою: кожна правка `no-secrets.mjs` чи його спеки його зсуває.
 * Тому він датований наявним комітом, а не «сьогодні»: датоване число можна
 * перевірити через рік, недатоване старіє мовчки. Несуче в ньому все одно не
 * число, а те, що ці два файли достатньо великі, аби їх виключення щось важило.
 *
 * Нуль, і не випадково: шаблону «довгий base64» тут немає за задумом (див. коментар
 * до `PATTERNS`), тож 410 рядків `integrity` спрацювати не можуть. Виключення
 * `package-lock.json` знімало ще й нагляд за `url-credentials` у `resolved` —
 * класичним витоком саме через lock. Чотири `.png` тепер відсіює `isBinary`, тобто
 * детектор, а не список.
 *
 * `SELF_DESCRIBING` теж виміряно: 0 знахідок, тобто сьогодні він інертний. Лишається
 * зі СТРУКТУРИ — цей файл оголошує шаблони, і шаблон, дописаний ширше, здатен
 * збігтися з власним джерелом. Текст плану сюди НЕ додається: його фікстури зібрані
 * з частин, тож виняток на цілий файл не потрібен.
 */
const SELF_DESCRIBING = [
  'scripts/verify/checks/no-secrets.mjs',
  'tests/unit/no-secrets.spec.ts',
];

function isExcluded(relPath) {
  return SELF_DESCRIBING.includes(relPath);
}

/**
 * Ознаки того, що збіг — плейсхолдер у документації, а не ключ.
 *
 * Це ТРЕТІЙ пропуск перевірки, нарівні з бінарними й поіменним виключенням, і він
 * має ті самі чотири властивості: названий тут, продубльований у `blindSpot`,
 * порахований і надрукований у підсумку КОЖНОГО прогону, виправданий виміром.
 *
 * Вимір на справжньому периметрі (ті самі 95 файлів, що читає звичайний прогін):
 * **придушено 2 збіги**, обидва в `docs/superpowers/plans/…` — `bearer-token` і
 * `assigned-secret`, тобто фікстури з тексту плану. Обидва числа тут не треба
 * перевіряти окремою командою: їх друкує підсумковий рядок КОЖНОГО звичайного
 * прогону, тож застаріти мовчки вони не можуть. Без цього відсіву звичайний
 * прогін був би ЧЕРВОНИЙ двома не-секретами. Користь ненульова, тож за тим самим
 * правилом, що скасувало виключення lock-файлів, цей пропуск лишається — але
 * лишається ВИДИМИМ: мовчазний відсів нічим не кращий за мовчазне виключення.
 */
const PLACEHOLDER = /\$\{|<[A-Za-z_]|YOUR[_-]|EXAMPLE|SAMPLE|PLACEHOLDER|CHANGE[_-]?ME|xxxx|…|\.\.\./i;

/**
 * Шаблони. Назва кожного потрапляє у звіт — щоб той, хто читає, знав, що саме шукати
 * у файлі, не отримавши самого рядка.
 *
 * Кожен прив'язаний до КОНТЕКСТУ (R-14): слово-якір (`api_key`, `secret`, `token`,
 * `password`, `aisstream`, `Bearer `), форма URL із креденшелами, або літеральний
 * префікс блоку (`-----BEGIN … PRIVATE KEY-----`, `AKIA`/`ASIA`). Жодного шаблону
 * «довгий base64» чи «довгий hex» тут немає й бути не може: саме вони роблять
 * перевірку червоною на дайджестах, хешах і data-URI, тобто на не-секретах.
 */
const PATTERNS = [
  { name: 'private-key-block', re: /-----BEGIN(?: [A-Z]+)* PRIVATE KEY-----/g },
  { name: 'url-credentials', re: /\b[a-z][a-z0-9+.-]*:\/\/[^/\s:@'"]+:[^/\s:@'"]+@/g },
  { name: 'aws-access-key-id', re: /\b(?:AKIA|ASIA)[0-9A-Z]{16}\b/g },
  // Той самий клас, що AKIA/ASIA (R-34): літеральний префікс, жодної ентропії.
  // Ключ із таким префіксом упізнається САМ, без слова-якоря поруч, — і це
  // несуче, бо виміряно, що гола форма `const a = "sk-…"` не мала жодного
  // шаблону, який би її взяв, а ключ і приходить у таку змінну.
  { name: 'sk-prefixed-key', re: /\bsk-[A-Za-z0-9_-]{16,}/g },
  { name: 'bearer-token', re: /\bBearer\s+[A-Za-z0-9._~+/-]{16,}={0,2}/g },
  {
    // Дві межі тут виміряні, а не вгадані.
    //
    // Ліва: `\b` перед словом-якорем вимагав, щоб попередній символ НЕ був
    // символом слова, — а `_` ним є. Тому `ANTHROPIC_AUTH_TOKEN: "…"`, тобто
    // дослівна форма живого токена в `.claude/settings.local.json`, шаблону не
    // давалася зовсім. Замість `\b` — «не літера й не цифра»: підкреслення
    // перед якорем тепер дозволене, бо саме так іменують змінні оточення.
    //
    // Права: між ключем і роздільником буває ЗАКРИВНА лапка — `"API_KEY": "…"`
    // у JSON. Без неї шаблон вимагав `:` одразу після слова й на JSON не
    // спрацьовував (виміряно окремо від першої причини: форми різні).
    name: 'assigned-secret',
    re: /(?<![A-Za-z0-9])(?:api[_-]?key|apikey|secret|token|password|passwd|access[_-]?key|auth[_-]?key)(?![A-Za-z0-9])['"`]?\s*[:=]\s*['"`]?[A-Za-z0-9._~+/-]{16,}={0,2}/gi,
  },
  // Мотивувальний випадок R2: ключ AISStream, названий у CLAUDE.md поіменно.
  { name: 'aisstream-key', re: /\baisstream\b[^\n]{0,40}?['"`][A-Za-z0-9]{16,}['"`]/gi },
];

/** Бінарь виявляється NUL-байтом, а не розширенням: список розширень старіє, детектор ні. */
function isBinary(buffer) {
  return buffer.subarray(0, 8192).includes(0);
}

/**
 * Повертає лише метадані збігу. Сам збіг не залишає цієї функції — за побудовою.
 *
 * `stats` — необов'язковий лічильник придушених плейсхолдером збігів. Вихідний
 * параметр, а не друге повернуте поле, з двох причин: виклик `scanLine(line)`
 * лишається тим, чим був (масив збігів, довжина якого і є їх кількістю), і рядок
 * обходиться шаблонами ОДИН раз, а не двічі заради підрахунку.
 */
export function scanLine(line, stats = null) {
  const found = [];

  for (const pattern of PATTERNS) {
    // ЦЕЙ РЯДОК НЕ ДОВЕДЕНИЙ ЖОДНИМ ТЕСТОМ, і це виміряно, а не недогляд: зняти
    // його — сюїта лишається зеленою (91 passed станом на c8d7cc5). Причина в тому, що
    // `exec` на глобальному регексі, не знайшовши збігу, САМ скидає `lastIndex` у
    // нуль, а цикл нижче завжди доходить до цього null. Виміряно позатрековим
    // зондом на /\bX[0-9]{3}\b/g і рядку `X111 та ще X222`: після вичерпаного
    // циклу `lastIndex` дорівнює 0, після ОДНОГО `exec` — 4, тобто ненульовий.
    // Число залежить від входу; несуче тут «нуль проти ненуля», а не сама четвірка.
    //
    // Отже рядок стає несучим тоді й тільки тоді, коли цикл перестане
    // вичерпуватися: `while` замінять на `if`, або з'явиться достроковий вихід —
    // скажімо, `break` на ліміті знахідок з одного рядка. Перший із цих випадків
    // ловить тест «scanLine бачить УСІ збіги рядка», решта — ні. Рядок лишається
    // як варта на всі них, але видавати його за доведений не можна.
    pattern.re.lastIndex = 0;
    let match = pattern.re.exec(line);
    // Саме `while`, а не `if`: у рядку може бути кілька збігів одного шаблону, і
    // другий із них — так само знахідка, як перший.
    while (match !== null) {
      if (PLACEHOLDER.test(match[0])) {
        if (stats !== null) stats.placeholderSuppressed += 1;
      } else {
        found.push({ pattern: pattern.name, length: match[0].length });
      }
      match = pattern.re.exec(line);
    }
  }

  return found;
}

/**
 * Чиста функція за R-12: бере корінь, повертає ЛИШЕ метадані — file, line, назву
 * шаблону, довжину збігу — плюс три лічильники. Самого збігу вона не повертає, тож
 * навіть той, хто викличе її з тесту, не зможе випадково надрукувати знайдене.
 */
export function scanForSecrets(root) {
  const findings = [];
  const stats = { placeholderSuppressed: 0 };
  let scanned = 0;
  let binarySkipped = 0;
  let excludedSkipped = 0;
  let vanished = 0;

  for (const relPath of listRepoFiles(root)) {
    if (isExcluded(relPath)) {
      excludedSkipped += 1;
      continue;
    }

    let buffer;
    try {
      buffer = readFileSync(path.join(root, relPath));
    } catch (error) {
      // R-05, той самий прецедент, що й ENOENT-гілка варти читання в `sourceHash`
      // (`hash.mjs`), де зниклий файл дає сентинел: між `git ls-files` і читанням
      // файл може зникнути. Терпимо САМЕ ENOENT, поіменно — будь-яка інша помилка
      // читання (права, зламаний диск) летить угору, бо мовчазне «просканували»
      // на нечитаному файлі і є та підміна, від якої весь шар.
      if (error.code !== 'ENOENT') throw error;
      vanished += 1;
      continue;
    }

    if (isBinary(buffer)) {
      binarySkipped += 1;
      continue;
    }

    scanned += 1;
    buffer.toString('utf8').split('\n').forEach((line, index) => {
      for (const item of scanLine(line, stats)) {
        findings.push({ file: relPath, line: index + 1, ...item });
      }
    });
  }

  return {
    findings,
    scanned,
    binarySkipped,
    excludedSkipped,
    placeholderSuppressed: stats.placeholderSuppressed,
    vanished,
  };
}

function main() {
  const root = process.argv.slice(2).find((arg) => !arg.startsWith('-')) ?? process.cwd();
  const {
    findings, scanned, binarySkipped, excludedSkipped, placeholderSuppressed, vanished,
  } = scanForSecrets(root);

  // Нуль оглянутих файлів — ПРОВАЛ кроку, не успіх. Досяжно звичайним аргументом
  // кореня (`no-secrets.mjs node_modules`), і без цієї варти давало «знахідок
  // немає» з кодом 0, тобто PASSED від перевірки, яка не прочитала нічого. Саме це
  // й є характерний провал цього шару: статус читається як успіх, коли не бігло
  // нічого.
  //
  // Варта стоїть у `main()`, а не в `scanForSecrets`: бібліотечна функція має повне
  // право дістати порожню фікстуру — це законний тест. Бреше межа ПРОГРАМИ, там
  // варта й потрібна.
  //
  // Код 2, не 1. `classifyExit` у `run.mjs` мапить обидва у FAILED — обидва падають
  // у її останній `return`, — тож блокує однаково. Ненульовий код туди доходить НЕ
  // завжди: 127 і 126 мають у ній власні гілки й дають UNRUNNABLE, а не FAILED
  // (пінить тест «classifyExit: ENOENT, 127, 126, таймаут — UNRUNNABLE, ніколи
  // FAILED»). Для 1 і 2 це байдуже, для вибору третього коду — ні.
  // 2 відрізняє «не було чого сканувати» від «знайдено ключ» для того,
  // хто дивиться на голий код виходу. Прецедент у цьому ж файлі — `catch` нижче.
  if (scanned === 0) {
    process.stderr.write(
      `no-secrets: у периметрі ${root} немає жодного файлу для огляду — `
      + 'перевірка нічого не оглянула й тому нічого не довела.\n',
    );
    process.exit(2);
  }

  for (const item of findings) {
    process.stdout.write(`${item.file}:${item.line}: ${item.pattern} (довжина збігу: ${item.length})\n`);
  }

  // ВСІ ТРИ пропуски названо в підсумку — і на зеленому теж. Пропуск, про який
  // мовчать, читається як «перевірено», а це рівно та підміна, від якої весь шар.
  // Зниклі файли — окремо й лише коли їх не нуль: у нормальному прогоні рядок не
  // росте, у ненормальному не мовчить.
  const skipped = `пропущено бінарних — ${binarySkipped}, поза периметром — ${excludedSkipped}`
    + `, придушено плейсхолдером — ${placeholderSuppressed}`
    + (vanished > 0 ? `, зникло під час читання — ${vanished}` : '');

  if (findings.length === 0) {
    process.stdout.write(
      `no-secrets: просканували файлів — ${scanned}, ${skipped}, знахідок немає.\n`,
    );
    process.exit(0);
  }

  const affected = new Set(findings.map((item) => item.file)).size;
  process.stdout.write(
    `no-secrets: знахідок — ${findings.length}, файлів із знахідками — ${affected}, `
    + `${skipped}. Вміст не друкується — відкрийте файл за вказаним рядком.\n`,
  );
  process.exit(1);
}

// R-22. Варта обов'язкова: за R-12 тест імпортує `scanForSecrets` із цього ж файлу,
// і без неї імпорт запускав би `main()` із `process.exit()` посеред тестів. Форма —
// у `entry-point.mjs`, туди ж переїхав вимір, який її пояснює.
//
// Правило трьох, записане тут раундом раніше, спрацювало: копій стало чотири (ще
// `run.mjs` і `hash.mjs`, обидві наївні й обидві виміряні), тож варта переїхала у
// спільний модуль разом із цими двома. Ціна помилки саме тут вища за середню: рядок
// реєстру має `needs: []` — за R-72 біжить неохороненим — і `emptyProbe` в нього
// немає, тож мовчазне зелене нікому було б спіймати.
if (isEntryPoint(import.meta.filename)) {
  try {
    main();
  } catch (error) {
    process.stderr.write(`no-secrets: перевірка не змогла запуститися: ${error.message}\n`);
    process.exit(2);
  }
}
