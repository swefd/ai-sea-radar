import { test as base, expect, type Page } from '@playwright/test';

import { DEMO_TICK_MS } from '@/entities/vessel';
import { OSM_TILE_LAYER } from '@/shared/config';

// Тести вибору, B-07. Джерело вимог: docs/tasks/SPRINT-01.md:38 — "на сторінці
// три елементи з `data-vessel-id`; клік по судну відкриває картку з його `id`;
// повторний клік її не закриває; запити до тайлів заблоковані".
//
// ЧОГО ЦЯ СЮЇТА НЕ ДОВОДИТЬ, і це вимога того ж завдання (SPRINT-01.md:78):
// РУХУ ВОНА НЕ ПЕРЕВІРЯЄ. Автоматична перевірка руху з керованим часом — робота
// релізу R3; цього тижня рух перевірено очима, і в записі checkpoint це так і
// записується. Так само нічого не сказано про зображення карти (тайли свідомо
// заблоковані) і про формати картки (їх пінять юніт-тести).
//
// НЕСУЧЕ ОБМЕЖЕННЯ, ЩО ТРИМАЄ СЮЇТУ НЕХИТКОЮ. Демонстраційний флот рухається:
// раз на 2000 мс кожне судно переходить у наступну точку, і так 22 секунди.
// Тому тут НЕ МОЖНА стверджувати нічого, що змінюється з тіком — ні координат,
// ні часу повідомлення, ні позиції значка на екрані. Усе, що стверджується
// нижче, від тіка не залежить: кількість суден, їхні `id`, назва та те, яка
// картка відкрита. Судно під курсором стрибає, але Playwright перед кліком
// перевіряє стабільність елемента й влучання в ціль, а `id` значка переживає
// будь-яку кількість тіків — маркер на зміну даних не перестворюється
// (§3.3 проєктного рішення B-03/B-04). Виміряно розвідкою перед написанням:
// шість кліків по судну, що рухається, з інтервалом 1.9 с — шість влучань,
// жодного провалу; окремо заміряний клік зайняв 37 мс.

/**
 * Хости, які тест вважає своїми. Решта інтернету для нього не існує.
 *
 * Пара, а не похідне від `baseURL`, свідомо: якщо колись dev-сервер переїде на
 * інший інтерфейс, тести впадуть ГУЧНО (заблокують сам застосунок), а не тихо
 * почнуть ходити в мережу. З двох напрямків помилки обрано гучний.
 */
const LOOPBACK_HOSTS = new Set(['127.0.0.1', 'localhost']);

/**
 * Схеми, які взагалі можуть піти в мережу. Без цього рядка предикат нижче
 * скасовував би ще й `data:` та `blob:`, у яких `hostname` — порожній рядок:
 * жодного такого запиту сьогодні немає (виміряно: перехоплено 16 запитів, усі
 * до тайлів), але мовчазне скасування схеми, що мережі й не торкається, було б
 * пасткою для того, хто колись додасть вбудоване зображення.
 */
const NETWORK_PROTOCOLS = new Set(['http:', 'https:']);

function isExternal(rawUrl: string | URL): boolean {
  const url = typeof rawUrl === 'string' ? new URL(rawUrl) : rawUrl;
  return NETWORK_PROTOCOLS.has(url.protocol) && !LOOPBACK_HOSTS.has(url.hostname);
}

/**
 * Хост тайлів ВИВОДИТЬСЯ з конфігурації застосунку, а не переписується сюди
 * рядком: правило CLAUDE.md "кожне погоджене значення живе в одному місці".
 * Зміниться шар тайлів — зміниться й те, що шукає перевірка нижче.
 */
const TILE_HOST = new URL(OSM_TILE_LAYER.urlTemplate).hostname;

interface Traffic {
  /** Запити назовні, які перехоплено й скасовано. */
  readonly blocked: string[];
  /** Відповіді з не-loopback хостів. Мусить лишитися порожнім. */
  readonly escaped: string[];
}

/**
 * Блокування ЗА ДОЗВОЛЕНИМ, а не за забороненим: скасовується все, що не
 * loopback, замість глоба на конкретний хост тайлів.
 *
 * Різниця не косметична. Глоб `**tile.openstreetmap.org**` перестає збігатися
 * тієї миті, коли хтось міняє `OSM_TILE_LAYER.urlTemplate` — і тест мовчки
 * повертається до залежності від мережі, лишаючись зеленим. Предикат від такої
 * правки не страждає: новий хост так само не loopback.
 *
 * Фікстура `auto`, а не щось, що тест мусить не забути попросити: перевірка,
 * яку можна пропустити, забувши аргумент, — не перевірка.
 */
const test = base.extend<{ traffic: Traffic }>({
  traffic: [
    async ({ page }, use) => {
      const blocked: string[] = [];
      const escaped: string[] = [];

      // Ставиться ДО `goto` (фікстури `auto` виконуються перед `beforeEach`),
      // інакше перші запити тайлів пішли б у мережу до встановлення маршруту.
      await page.route(
        (url) => isExternal(url),
        async (route) => {
          blocked.push(route.request().url());
          await route.abort();
        },
      );

      // Друга половина доказу, і саме вона ловить витік. Скасований запит
      // відповіді не має за визначенням, тож будь-яка відповідь із чужого
      // хоста означає, що повз маршрут пройшов запит, якого перевірка не
      // бачила: service worker, префетч браузера, будь-що.
      page.on('response', (response) => {
        if (isExternal(response.url())) {
          escaped.push(response.url());
        }
      });

      await use({ blocked, escaped });

      // Прибирання фікстури — після тіла КОЖНОГО тесту, не лише того, що
      // перевіряє тайли. Мережа має лишатися недосяжною весь прогін.
      expect(escaped, 'із зовнішніх хостів надійшла відповідь — блокування протікло').toEqual([]);
    },
    { auto: true },
  ],
});

/**
 * Значення поля картки за його підписом.
 *
 * Пошук іде за ПІДПИСОМ, а не за номером рядка: `nth(1)` зеленів би й тоді,
 * коли картка друкує в полі "Ідентифікатор" щось інше, аби воно стояло другим.
 */
function cardField(page: Page, label: string) {
  return page
    .locator('aside dl > div')
    .filter({ has: page.locator('dt', { hasText: label }) })
    .locator('dd');
}

/** Картка на сторінці рівно одна, і належить вона панелі. */
function card(page: Page) {
  return page.locator('aside dl');
}

test.beforeEach(async ({ page }) => {
  await page.goto('/');

  // Очікування готовності, а не перевірка: карта вантажиться окремим чанком
  // (`ssr: false`), тож до першого значка проходить помітний час. Твердження
  // про кількість суден живе у власному тесті нижче.
  await page.locator('[data-vessel-id]').first().waitFor();
});

test('на сторінці рівно три судна, і кожне знаходиться за data-vessel-id', async ({ page }) => {
  const vessels = page.locator('[data-vessel-id]');

  await expect(vessels).toHaveCount(3);

  // Не просто "три штуки", а саме ті три: підрахунок сам по собі лишався б
  // зеленим, якби три значки належали одному судну.
  const ids = await vessels.evaluateAll((nodes) =>
    nodes.map((node) => node.getAttribute('data-vessel-id')),
  );
  expect(ids.slice().sort()).toEqual(['demo-1', 'demo-2', 'demo-3']);

  // Кожне судно має і другий атрибут ТЗ — інакше тести шукали б значки за
  // тим, чого домовленість не гарантує.
  await expect(page.locator('[data-vessel-id][data-icon]')).toHaveCount(3);

  // ВАРТА ПІДРАХУНКУ. Картка свідомо не несе `data-vessel-id`
  // (коментар у ui/vessel-card.tsx), і тримається це тільки тут: варто комусь
  // додати атрибут картці — і на сторінці стане чотири збіги, тобто цей тест
  // почне рахувати судна неправильно, лишаючись зеленим на перших рядках.
  await page.locator('[data-vessel-id="demo-1"]').click();
  await expect(vessels).toHaveCount(3);
  await expect(page.locator('aside [data-vessel-id]')).toHaveCount(0);
});

test('клік по судну відкриває картку САМЕ цього судна', async ({ page }) => {
  // Спершу картки немає. Без цього рядка тест був би зелений і над карткою,
  // що висить від початку й ніколи не міняється.
  await expect(card(page)).toHaveCount(0);

  // Три судна поспіль: одне не відрізнило б картку "за обраним id" від картки,
  // прибитої до єдиного судна. Заразом це робить спостережною вимогу ТЗ
  // "картка закривається тільки вибором іншого судна" — до B-05 перемикатися
  // не було на що.
  for (const id of ['demo-2', 'demo-1', 'demo-3']) {
    await page.locator(`[data-vessel-id="${id}"]`).click();

    await expect(card(page)).toHaveCount(1);
    await expect(cardField(page, 'Ідентифікатор')).toHaveText(id);
    // Назва приходить із того самого судна — доказ, що картка взяла ВСЕ судно
    // за обраним id, а не підставила id у чужі поля.
    await expect(cardField(page, 'Назва')).toHaveText(`Демо-судно ${id.slice(-1)}`);
  }
});

test('повторний клік по тому самому судну картки не закриває', async ({ page }) => {
  const vessel = page.locator('[data-vessel-id="demo-2"]');

  await vessel.click();

  // Проміжне твердження обов'язкове: без нього тест проходив би й тоді, коли
  // картка не відкривалася жодного разу — "закрито" й "ніколи не відкривалося"
  // на екрані виглядають однаково.
  await expect(card(page)).toHaveCount(1);
  await expect(cardField(page, 'Ідентифікатор')).toHaveText('demo-2');

  // Другий клік — свідомо ПІСЛЯ ЦІЛОГО ТІКА, тобто по судну, яке встигло
  // переїхати в наступну точку. Пауза рахується з `DEMO_TICK_MS`, а не з
  // літерала: зміниться тік — зміниться й вона, і намір лишиться цілим.
  //
  // Межа рядка названа чесно, бо спокуса обіцяти більше велика: сюїта НЕ
  // стверджує, що тік справді стався — це була б перевірка руху, якої B-07 не
  // робить за вимогою SPRINT-01.md:78. Доведено рівно те, що вибір працює й
  // через дві секунди після першого кліку. Що маркер при цьому пережив
  // оновлення даних, показали очі й мутація E2, а не цей рядок.
  await page.waitForTimeout(DEMO_TICK_MS + 200);
  await vessel.click();

  await expect(card(page)).toHaveCount(1);
  await expect(cardField(page, 'Ідентифікатор')).toHaveText('demo-2');

  // КОНТРОЛЬ ЖИВОСТІ, і без нього твердження вище неповне. "Картка лишилася
  // відкритою" однаково пояснюється і правильною поведінкою, і тим, що другий
  // клік нікуди не дійшов — наприклад, якби обробник загубився при оновленні
  // даних на тіку. Клік по ТРЕТЬОМУ судну мусить картку перемкнути; якщо він
  // теж нічого не робить, вибір мертвий, і рядок вище нічого не доводив.
  await page.locator('[data-vessel-id="demo-3"]').click();
  await expect(cardField(page, 'Ідентифікатор')).toHaveText('demo-3');
});

test('запити до тайлів заблоковані — тест не залежить від мережі', async ({ page, traffic }) => {
  // Карта живе й без тайлів: значки — це наш DOM поверх контейнера Leaflet, а
  // не частина зображення. Рядок стоїть першим, щоб провал читався як "карта
  // не піднялася", а не як "тайли не заблоковані".
  await expect(page.locator('.leaflet-container')).toBeVisible();
  await expect(page.locator('[data-vessel-id]')).toHaveCount(3);

  const tiles = traffic.blocked.filter((url) => new URL(url).hostname === TILE_HOST);

  // ПОЗИТИВНА половина доказу. Нуль тут — не "чисто", а зламана перевірка:
  // означав би, що шар тайлів не просив жодного зображення, тобто блокування
  // стерегло б порожнечу. Саме цим рядком тест відрізняє "заблоковано" від
  // "не було чого блокувати".
  expect(tiles.length, `жодного запиту до ${TILE_HOST} не перехоплено`).toBeGreaterThan(0);

  // НЕГАТИВНА половина — у прибиранні фікстури, і вона працює в кожному тесті
  // файлу, а не лише в цьому: `escaped` мусить лишитися порожнім.
  expect(traffic.escaped).toEqual([]);

  // Єдина діра, якої `page.route` не бачить за побудовою: запити, що йдуть із
  // service worker. Застосунок жодного не реєструє, і саме це тут і
  // стверджується — припущення стає перевіреним фактом ціною одного рядка.
  const serviceWorkers = await page.evaluate(async () => {
    if (!('serviceWorker' in navigator)) {
      return 0;
    }
    const registrations = await navigator.serviceWorker.getRegistrations();
    return registrations.length;
  });
  expect(serviceWorkers, 'зареєстровано service worker — повз маршрут може ходити мережа').toBe(0);
});
