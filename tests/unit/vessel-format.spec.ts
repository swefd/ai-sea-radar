test('джерело: обидва значення VesselSource мають підпис', () => {
  expect(formatSource('demo')).toBe('Демонстраційні дані');
  expect(formatSource('aisstream')).toBe('AISStream');
  expect(formatSource('demo')).toBe(SOURCE_LABELS.demo);
  expect(formatSource('aisstream')).toBe(SOURCE_LABELS.aisstream);

  // Склад таблиці закріплено поіменно: поява третього джерела без підпису дала б
  // undefined на екрані, а Record<VesselSource, string> цього не ловить — тип
  // оновили б тим самим рухом. Це той самий прийом, що й у hash.spec.ts для
  // периметра: перелік міняється свідомо й під рев'ю.
  expect(Object.keys(SOURCE_LABELS).sort()).toEqual(['aisstream', 'demo']);
});

// -------------------------------------------------------------------- назва

test('назва: null — "Немає даних", решта повертається як є', () => {
  expect(formatName(null)).toBe(UNKNOWN_VALUE);
  expect(formatName('Демо-судно 1')).toBe('Демо-судно 1');

  // Порожній рядок НЕ перетворюється тут: за узгодженою структурою нормалізація
  // "" -> null належить входу даних, а не форматувальнику. Якби тут стояло `||`,
  // цей рядок повернув би "Немає даних" — і дефект був би невидимий, поки не
  // приїдуть справжні дані AIS із безіменним судном.
  expect(formatName('')).toBe('');
});

test('назва: теги лишаються символами — екранує JSX, а не форматувальник', () => {
  // Критерій приймання B-03/B-04 №4. Тут перевіряється рівно половина вимоги:
  // форматувальник НЕ чіпає рядок (ні escape, ні strip). Друга половина — що JSX
  // рендерить його як текст, а не HTML, — належить картці й доводиться очима
  // цього тижня, e2e — у B-07.
  expect(formatName('<b>Демо</b>')).toBe('<b>Демо</b>');
  expect(formatName('<b>Демо</b>')).toContain('<b>');
  expect(formatName('&amp;')).toBe('&amp;');
});
