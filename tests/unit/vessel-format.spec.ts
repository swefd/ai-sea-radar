import { test, expect } from '@playwright/test';

import {
  UNKNOWN_VALUE,
  SOURCE_LABELS,
  formatCoordinates,
  formatSpeed,
  formatCourse,
  formatTimestamp,
  formatSource,
  formatName,
} from '@/entities/vessel';

// Формати картки судна: ТЗ (CLAUDE.md, "Card formats") і §3.5 проєктного рішення
// B-03/B-04.
//
// ЧОМУ ЦЕ НЕ ЗВИЧАЙНА СЮЇТА — і це головна знахідка §7 того рішення. Кожен до одного
// літерал ТЗ (51.00000, 1.45678 / 12.3 kn / 12 kn / 0 kn / 135° / 12:00:00 UTC) дає
// ОДНАКОВИЙ вихід під ОБОМА читаннями кожної неоднозначності: і при round-потім-модуль,
// і при модуль-потім-округлення; і при toFixed(1), і при Math.round(x*10)/10; і при
// годиннику UTC, і при локальному. Сюїта з самих лише прикладів ТЗ була б зелена над
// трьома різними дефектами — рівно та "зелена сюїта, що не стереже", про яку попереджає
// CLAUDE.md. Тому нижче в кожному розділі є випадки РОЗХОДЖЕННЯ, і в кожного названо,
// що саме він ловить і що дав би невірний варіант.
//
// Імпорт — тільки з чистого входу '@/entities/vessel'. Жодного разу з ui/: юніт-раннер
// Playwright не має трансформу для .css і дає ERR_UNKNOWN_FILE_EXTENSION ".css" (§3.1).

const TZ_INDEPENDENT_TIMESTAMP = '2026-09-18T12:00:00.000Z';

test('UNKNOWN_VALUE — точний рядок ТЗ, з точністю до кодових позицій', () => {
  expect(UNKNOWN_VALUE).toBe('Немає даних');

  // П'ята літера — U+0454 (українське "є"), а НЕ U+0435 ("е"). У рев'ю ці два
  // рядки не відрізнити на око, тож звичайне порівняння рядків тут стереже лише
  // доти, доки цей файл не передрукували з клавіатури разом із джерелом. Пін за
  // кодовою позицією ловить саме передрук (§3.5, "Дві дрібниці, що коштують годину").
  expect(UNKNOWN_VALUE.codePointAt(4)).toBe(0x0454);
});

// ---------------------------------------------------------------- координати

test("координати: п'ять знаків із хвостовими нулями", () => {
  // Літерал ТЗ.
  expect(formatCoordinates(51, 1.45678)).toBe('51.00000, 1.45678');
  // Хвостові нулі зберігаються обабіч коми-роздільника, не лише зліва.
  expect(formatCoordinates(51.0421, 1.4237)).toBe('51.04210, 1.42370');
  // Від'ємні півкулі: знак не губиться й не з'їдає розряд.
  expect(formatCoordinates(-0.5, -1.25)).toBe('-0.50000, -1.25000');
  // Округлення до п'ятого знака, включно з переносом через одиницю.
  expect(formatCoordinates(51.123456, 1.999999)).toBe('51.12346, 2.00000');
});

test('координати: десятковий роздільник — крапка, а не кома (варта проти Intl)', () => {
  // (51).toLocaleString('uk-UA', { minimumFractionDigits: 5 }) дає "51,00000", і
  // пара координат вийшла б із ЧОТИРМА комами, з яких лише одна — роздільник пари.
  // Обидва літерали ТЗ мають крапки, тож тест вище впіймав би й це; цей рядок
  // лишається окремо тому, що формулює вимогу як інваріант форми, а не як збіг
  // з одним прикладом — і тримає її на входах, яких у ТЗ немає.
  for (const [lat, lon] of [[51, 1.45678], [0, 0], [-0.5, -1.25], [50.75, 1.95]] as const) {
    expect(formatCoordinates(lat, lon)).toMatch(/^-?\d+\.\d{5}, -?\d+\.\d{5}$/);
  }
});

// ----------------------------------------------------------------- швидкість

test('швидкість: літерали ТЗ і хвостовий нуль, якого не має бути', () => {
  expect(formatSpeed(12.3)).toBe('12.3 kn');
  // "12 kn", не "12.0 kn": Number() зрізає хвостовий нуль, який лишає toFixed.
  expect(formatSpeed(12)).toBe('12 kn');
});

test('швидкість: 0 — це 0 kn, і лише null — "Немає даних"', () => {
  // Пряма варта проти `||` замість `??` (і проти `if (!speedKnots)`). Судно, що
  // справді стоїть, мусить показувати нуль вузлів, а не "невідомо": це рядок ТЗ
  // "Нуль і null - різні речі" і половина US-04.
  expect(formatSpeed(0)).toBe('0 kn');
  expect(formatSpeed(null)).toBe(UNKNOWN_VALUE);
  expect(formatSpeed(null)).toBe('Немає даних');
});

test('швидкість: округлення — саме toFixed, не Math.round(x*10)/10', () => {
  // Розвилка, виміряна в §3.5: два способи розійшлися на 160 із 4000 значень.
  // Праворуч у кожному рядку — що надрукував би невірний варіант.
  expect(formatSpeed(0.95)).toBe('0.9 kn'); // Math.round(9.5)/10 = 1   -> "1 kn"
  expect(formatSpeed(8.95)).toBe('8.9 kn'); // Math.round(89.5)/10 = 9  -> "9 kn"
  expect(formatSpeed(0.15)).toBe('0.1 kn'); // -> "0.2 kn"
  expect(formatSpeed(0.35)).toBe('0.3 kn'); // -> "0.4 kn"
  expect(formatSpeed(0.85)).toBe('0.8 kn'); // -> "0.9 kn"
  expect(formatSpeed(12.35)).toBe('12.3 kn'); // -> "12.4 kn"

  // Чому 8.95 дає 8.9, а не 9.0: toFixed округлює DOUBLE, а не десятковий літерал,
  // і найближчий до 8.95 double — 8.9499…. Очікування тут виміряне запуском, а не
  // виведене з правила "половина вгору"; саме тому воно й стереже.
});

test('швидкість: мінус нуль не доживає до екрана', () => {
  // (-0.04).toFixed(1) це "-0.0". Зрізання хвостового нуля регексом дало б
  // "-0 kn" — значення, якого не буває. Number() приводить рядок до -0, а
  // шаблонний рядок друкує -0 як "0".
  expect(formatSpeed(-0.04)).toBe('0 kn');
  expect(formatSpeed(-0.049)).toBe('0 kn');
  // Від'ємне, що НЕ округлюється до нуля, лишається від'ємним: варта, щоб
  // рядок вище не "полагодили" через Math.abs.
  expect(formatSpeed(-0.949)).toBe('-0.9 kn');
});

test('швидкість: форма виводу — крапка й суфікс kn (варта проти Intl)', () => {
  for (const value of [0, 0.15, 8.95, 12, 12.3, 1000.04]) {
    expect(formatSpeed(value), `швидкість ${value}`).toMatch(/^-?\d+(\.\d)? kn$/);
  }
});

// --------------------------------------------------------------------- курс

test('курс: літерали ТЗ і знак градуса саме U+00B0', () => {
  expect(formatCourse(135)).toBe('135°');
  expect(formatCourse(135.4)).toBe('135°');
  expect(formatCourse(135.5)).toBe('136°');

  // "°" (U+00B0) проти "º" (U+00BA, порядковий індикатор) на око не відрізнити.
  const rendered = formatCourse(135);
  expect(rendered.codePointAt(rendered.length - 1)).toBe(0x00b0);
});

test('курс: 0 — це 0°, і лише null — "Немає даних"', () => {
  // Друга половина вимоги "нуль і null - різні речі". Окремо небезпечно те, що
  // Math.round(null) дорівнює 0: незахищене округлення надрукувало б для
  // НЕВІДОМОГО курсу конкретне "0°", тобто збрехало б, а не змовчало.
  expect(formatCourse(0)).toBe('0°');
  expect(formatCourse(null)).toBe(UNKNOWN_VALUE);
  expect(formatCourse(null)).toBe('Немає даних');
});

test('курс: округлення ПЕРЕД модулем — межа домену [0, 360)', () => {
  // Центральний випадок розходження §3.5. `Math.round % 360` читається двома
  // способами, і вони дають різне рівно на [359.5, 360):
  //   round-потім-модуль (правильно): Math.round(359.7) = 360, 360 % 360 = 0
  //   модуль-потім-округлення:        359.7 % 360 = 359.7, Math.round = 360
  // Друге читання порушує домен [0, 360), оголошений у тому ж рядку ТЗ, тобто
  // друкує кут, якого тип не допускає. Жоден приклад із ТЗ цієї пари не розрізняє.
  expect(formatCourse(359.7)).toBe('0°'); // невірне читання -> "360°"
  expect(formatCourse(359.5)).toBe('0°'); // невірне читання -> "360°"

  // Нижній край вікна розходження: тут обидва читання згодні, і саме тому рядок
  // потрібен — він доводить, що вікно завширшки пів градуса, а не що функція
  // просто обнуляє все велике.
  expect(formatCourse(359.4)).toBe('359°');
});

test('курс: модуль справді працює, а не стоїть для краси', () => {
  // Без модуля обидва дали б "360°" і "720°" відповідно.
  expect(formatCourse(360)).toBe('0°');
  expect(formatCourse(720)).toBe('0°');
  // 719.7 ловить обидва дефекти одним входом: модуль-потім-округлення дає "360°",
  // відсутній модуль — "720°".
  expect(formatCourse(719.7)).toBe('0°');
});

test("курс: від'ємний кут проходить наскрізь — межа названа, не залатана", () => {
  // ВИМІРЯНО, і обидва читання §3.5 тут згодні: JS-оператор % зберігає знак
  // діленого, тож -45 лишається -45. Домен Vessel.courseDeg — [0, 360), тобто
  // такого входу не буває; рядок закріплює УХВАЛЕНУ формулу, а не бажану
  // поведінку. Якщо хтось замінить її на ((x % 360) + 360) % 360, тест почервоніє —
  // і це задумано: нормалізація від'ємних кутів була б новим рішенням, яке
  // ухвалюють у рев'ю, а не мовчазним поліпшенням тут.
  expect(formatCourse(-45)).toBe('-45°');
  // А от -0.4 округлюється до -0, і шаблонний рядок друкує його як "0".
  expect(formatCourse(-0.4)).toBe('0°');
});

// --------------------------------------------------------------------- час

test('час: літерал ТЗ і зміщення, що НЕ збігається з UTC', () => {
  expect(formatTimestamp(TZ_INDEPENDENT_TIMESTAMP)).toBe('12:00:00 UTC');
  // Несучий рядок: вхід із не-UTC зміщенням. Реалізація, що просто вирізає
  // символи [11, 19) З РЯДКА, надрукувала б "15:00:00 UTC" — тобто позначила б
  // київський час як UTC. Приклад ТЗ (той, що вже в Z) цього не розрізняє.
  expect(formatTimestamp('2026-09-18T15:00:00+03:00')).toBe('12:00:00 UTC');
  // Півгодинне зміщення: тут навіть арифметика по годинах не врятує.
  expect(formatTimestamp('2026-09-18T09:30:00-02:30')).toBe('12:00:00 UTC');
  // Перехід через добу назад: зміщення міняє не лише годину.
  expect(formatTimestamp('2026-09-19T01:00:00+13:00')).toBe('12:00:00 UTC');
});

test('час: годинник UTC, а не годинник машини', () => {
  const originalTz = process.env.TZ;
  try {
    for (const zone of ['Asia/Tokyo', 'Pacific/Kiritimati', 'America/Los_Angeles']) {
      process.env.TZ = zone;

      // Два несучі рядки, без яких тест був би зелений над будь-якою реалізацією.
      // Перший: зміна TZ на ходу СПРАВДІ вплинула на процес (Node перечитує змінну,
      // але покладатися на це наосліп — те саме, що не мати тесту).
      expect(Intl.DateTimeFormat().resolvedOptions().timeZone, zone).toBe(zone);
      // Другий: обрана зона справді розходиться з UTC на цю дату, інакше перевірка
      // нижче не розрізняла б локальний годинник від UTC-ішного.
      expect(new Date(TZ_INDEPENDENT_TIMESTAMP).getHours(), zone).not.toBe(12);

      // Реалізація через toLocaleTimeString або getHours() надрукувала б тут
      // "21:00:00 UTC" (Токіо) — час однієї зони з підписом іншої.
      expect(formatTimestamp(TZ_INDEPENDENT_TIMESTAMP), zone).toBe('12:00:00 UTC');
    }
  } finally {
    // Прибирання обов'язкове: воркер Playwright виконує наступні тести в цьому ж
    // процесі, і лишена зона протекла б у них.
    if (originalTz === undefined) {
      delete process.env.TZ;
    } else {
      process.env.TZ = originalTz;
    }
  }
});

test('час: нерозбірний рядок дає "Немає даних" і не кидає', () => {
  // new Date('не дата').toISOString() кидає RangeError і завалив би рендер УСІЄЇ
  // картки, а не одного поля. Гілка існує проти даних AIS, яких ще немає (§6).
  for (const bad of ['не дата', '', 'null', '2026-13-45T99:99:99Z']) {
    expect(() => formatTimestamp(bad), `вхід ${JSON.stringify(bad)}`).not.toThrow();
    expect(formatTimestamp(bad), `вхід ${JSON.stringify(bad)}`).toBe(UNKNOWN_VALUE);
  }
});

